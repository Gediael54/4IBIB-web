import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import * as XLSX from "xlsx";

const ROOT = process.cwd();
const XLSX_PATH = resolve(ROOT, "Escala de cultos.xlsx");
const OUT_PATH = resolve(ROOT, "supabase/seed.sql");
const BR_OFFSET_HOURS = 3;

const buffer = await readFile(XLSX_PATH);
const workbook = XLSX.read(buffer, { type: "buffer" });
const sheet = workbook.Sheets[workbook.SheetNames[0]];
const rows = XLSX.utils.sheet_to_json(sheet, { header: 1, raw: true, defval: null });

function excelDateTimeToIso(daySerial, timeFraction) {
  const days = daySerial - 25569;
  const seconds = Math.round((days * 86400) + (timeFraction || 0) * 86400);
  const ms = (seconds + BR_OFFSET_HOURS * 3600) * 1000;
  return new Date(ms).toISOString();
}

function ministryFor(title) {
  const t = (title || "").toLowerCase();
  if (t.startsWith("escola")) return "Escola Biblica";
  if (t.startsWith("encontro de mulheres")) return "Mulheres";
  if (t.includes("livre")) return "Geral";
  if (t.startsWith("culto")) return "Culto";
  return "Geral";
}

function parseRow(row) {
  const [date, , timeStart, timeEnd, rawTitle, eventId, director, preacher, leitura, special] = row;
  if (!date || !rawTitle) return null;

  let title = String(rawTitle).trim();
  let status = "scheduled";

  if (/livre/i.test(title)) {
    status = "free";
    title = "Livre";
  } else if (/\(\s*suspens[ao]\s*\)/i.test(title)) {
    status = "suspended";
    title = title.replace(/\s*\(\s*suspens[ao]\s*\)\s*/i, "").trim();
  }

  return {
    title,
    ministry: ministryFor(title),
    startsAt: excelDateTimeToIso(date, timeStart || 0),
    endsAt: excelDateTimeToIso(date, timeEnd || (timeStart || 0) + 90 / 1440),
    location: "Templo principal",
    summary: "",
    preacher: preacher ? String(preacher).trim() : "",
    director: director ? String(director).trim() : "",
    passage: leitura ? String(leitura).trim() : "",
    specialDate: special ? String(special).trim() : "",
    googleEventId: eventId ? String(eventId).trim() : "",
    status,
    featured: false
  };
}

const items = [];
for (let i = 1; i <= 212; i++) {
  const parsed = parseRow(rows[i]);
  if (parsed) items.push(parsed);
}

function sql(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  return `'${String(value).replace(/'/g, "''")}'`;
}

const lines = [
  "-- Generated by scripts/seed-from-xlsx.mjs from 'Escala de cultos.xlsx'.",
  "-- Re-running is safe: ON CONFLICT (google_event_id) updates the existing row.",
  "-- Self-contained: applies the schedule_items migration before inserting.",
  "begin;",
  "",
  "do $$",
  "begin",
  "  if exists (",
  "    select 1 from information_schema.columns",
  "    where table_schema = 'public' and table_name = 'schedule_items' and column_name = 'leader'",
  "  ) and not exists (",
  "    select 1 from information_schema.columns",
  "    where table_schema = 'public' and table_name = 'schedule_items' and column_name = 'preacher'",
  "  ) then",
  "    alter table public.schedule_items rename column leader to preacher;",
  "  end if;",
  "end $$;",
  "",
  "alter table public.schedule_items add column if not exists preacher text not null default '';",
  "alter table public.schedule_items add column if not exists director text not null default '';",
  "alter table public.schedule_items add column if not exists passage text not null default '';",
  "alter table public.schedule_items add column if not exists special_date text not null default '';",
  "alter table public.schedule_items add column if not exists google_event_id text not null default '';",
  "alter table public.schedule_items add column if not exists status text not null default 'scheduled';",
  "",
  "do $$",
  "begin",
  "  if not exists (",
  "    select 1 from information_schema.constraint_column_usage",
  "    where table_schema = 'public' and table_name = 'schedule_items' and constraint_name = 'schedule_status_valid'",
  "  ) then",
  "    alter table public.schedule_items",
  "      add constraint schedule_status_valid check (status in ('scheduled', 'suspended', 'free'));",
  "  end if;",
  "end $$;",
  "",
  "create unique index if not exists schedule_google_event_id_unique",
  "  on public.schedule_items (google_event_id)",
  "  where google_event_id <> '';",
  "",
  "create index if not exists schedule_starts_at_idx on public.schedule_items (starts_at);",
  ""
];

for (const item of items) {
  if (!item.googleEventId) continue;
  lines.push(
    [
      "insert into public.schedule_items",
      "  (id, title, ministry, starts_at, ends_at, location, summary, preacher, director, passage, special_date, google_event_id, status, featured)",
      "values (",
      `  gen_random_uuid(), ${sql(item.title)}, ${sql(item.ministry)}, ${sql(item.startsAt)}, ${sql(item.endsAt)},`,
      `  ${sql(item.location)}, ${sql(item.summary)}, ${sql(item.preacher)}, ${sql(item.director)}, ${sql(item.passage)},`,
      `  ${sql(item.specialDate)}, ${sql(item.googleEventId)}, ${sql(item.status)}, ${sql(item.featured)}`,
      ")",
      "on conflict (google_event_id) where google_event_id <> '' do update set",
      "  title = excluded.title,",
      "  ministry = excluded.ministry,",
      "  starts_at = excluded.starts_at,",
      "  ends_at = excluded.ends_at,",
      "  preacher = excluded.preacher,",
      "  director = excluded.director,",
      "  passage = excluded.passage,",
      "  special_date = excluded.special_date,",
      "  status = excluded.status;"
    ].join("\n")
  );
}

lines.push("commit;", "");

await writeFile(OUT_PATH, lines.join("\n"));
console.log(`Wrote ${items.length} schedule items to ${OUT_PATH}`);
